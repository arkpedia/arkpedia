export interface SkillResult {
  productivity?: number; // decimal, e.g. 0.15 for +15%
  capacity?: number;
  selfMorale?: number; // decimal per hour, positive = more consumption -- THIS operator only, not room-wide
  overridesOthersProductivity?: boolean; // Automation/Snegurochka family
  exemptFromOverride?: boolean; // survives even when another skill in this Factory overrides everyone else's productivity (confirmed case: Purestream vs. Snegurochka/Automation)
  note?: string; // shown in the UI if this result depends on an assumption
  formula?: string; // human-readable derivation of the productivity/capacity number above, shown in the "explain this facility" breakdown -- e.g. "0.05 x Felvine(12) = +60%". Optional and populated incrementally, not required on every handler.
}

type Handler = (ctx: FactorySkillContext) => SkillResult;

/** Keyed by "OperatorName|SkillName". Any skill in here has its ENTIRE
 * contribution computed by its handler, and is excluded from the
 * generic regex parser to avoid double-counting the plain-percentage
 * parts alongside the special-cased parts. */


/** Time-weighted average of Totter's morale-difference-dependent
 * productivity (own Morale decreasing linearly at his own rate,
 * productivity stepping down every 4 points of difference from full,
 * i.e. floor(diff/4)) over the facility's actual time window. Verified
 * against known breakpoints (diff=0 -> full value, diff=24 -> fully
 * capped) before wiring into the actual skill handlers. */
function totterProductivityAtDifference(diff: number, base: number, stepPer4: number, elite1Threshold: number | null, elite1Bonus: number): number {
  let value = base - stepPer4 * Math.floor(diff / 4);
  if (elite1Threshold !== null && diff > elite1Threshold) value += elite1Bonus;
  return value;
}

function totterAverageProductivity(
  selfMoraleRate: number,
  windowHours: number,
  base: number,
  stepPer4: number,
  elite1Threshold: number | null,
  elite1Bonus: number
): number {
  if (windowHours <= 0 || selfMoraleRate <= 0) {
    return totterProductivityAtDifference(0, base, stepPer4, elite1Threshold, elite1Bonus);
  }
  // Morale difference rises linearly with time at THIS operator's own
  // rate, capped at 24 (can't lose more morale than the 24 maximum).
  const breakpointsDiff = [0, 4, 8, 12, 16, 20, 24];
  const breakpointsTime = breakpointsDiff.map((d) => Math.min(windowHours, d / selfMoraleRate));
  let total = 0;
  for (let i = 0; i < breakpointsTime.length - 1; i++) {
    const t0 = breakpointsTime[i];
    const t1 = breakpointsTime[i + 1];
    if (t1 <= t0) continue;
    const segDiff = breakpointsDiff[i];
    total += totterProductivityAtDifference(segDiff, base, stepPer4, elite1Threshold, elite1Bonus) * (t1 - t0);
  }
  const lastT = breakpointsTime[breakpointsTime.length - 1];
  if (windowHours > lastT) {
    total += totterProductivityAtDifference(24, base, stepPer4, elite1Threshold, elite1Bonus) * (windowHours - lastT);
  }
  return total / windowHours;
}

