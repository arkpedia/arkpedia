import { nonDefaultRecruitSlots } from './baseResources';

export interface OfficeContext {
  officeLevel: number;
  totalDormitoryLevels: number;
  facilitiesWithEliteOperator: number;
  manualValue?: number; // meaning depends on the skill -- recruit slot count, Intelligence Reserve, etc.
  dormitoryCount: number;
  silverAshReignfrostInControlCenter: boolean;
  resourceBonuses: Record<string, number>;
  ursusSpecialtyBeverageTotal: number; // base-wide total, generated by Tachanka in the Control Center -- Blitz's HR speed scales with this
}

export interface OfficeSkillResult {
  hrSpeed?: number; // decimal, e.g. 0.20 for +20%
  selfMorale?: number; // decimal per hour, positive = more consumption -- THIS operator only, not room-wide
  receptionRoomClueSpeed?: number; // this Office skill's contribution to Reception Room, not Office itself
  note?: string;
}

type Handler = (ctx: OfficeContext) => OfficeSkillResult;

