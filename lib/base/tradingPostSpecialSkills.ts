import type { BaseRosters } from './baseGroupRosters';

export interface TradingPostContext {
  /** The group rosters (lib/base/baseGroupRosters.ts), from the page's props. */
  rosters: BaseRosters;
  manualValue?: number;
  sameRoomOperatorNames: string[]; // includes self
  filledCountThisRoom: number;
  dormitoryOperatorCount: number;
  distinctFactoryProductCount: number; // how many different products are currently being made across all Factories
  operatorFaction: (name: string) => string | null;
  ulpianusInBase: boolean;
  facilitiesWithSuiOperator: number;
  facilitiesWithEliteOperator: number; // confirmed explicit 7-name roster, not a rarity assumption -- see baseGroupRosters.ts
  othersOrderEfficiencySum?: number; // for Snowsant's self-referential skill
  othersOrderLimitRawSum?: number; // raw sum (including negatives) of OTHER operators' special-cased order limit contributions -- for Jaye's own effective-order-limit computation, since her orderEfficiency bonus depends on the actual final order limit, which depends partly on her own reduction computed in the same handler call. ALSO used by Degenbrecher's Champion's Bearing and Swire the Elegant Wit's Investment Solicitations -- confirmed both scale off this same net total, not a positive-only version.
  genericOrderLimitAdjustment?: number; // the generic (non-special-cased) order limit adjustment for this Trading Post, plus the fixed base -- for the same reason as above
  resourceBonuses: Record<string, number>;
  monsterMealTotal: number; // base-wide Monster Meal total, generated by Senshi's Diner in a Dormitory -- Chilchuck's order efficiency scales with this
  felvineTotal: number; // base-wide Felvine total, generated by Rathalos/Yato in the Control Center -- Terra Research Commission's order efficiency scales with this, exactly as its Factory skill scales productivity
  effectiveGoldLineCount: number; // base Pure Gold Production Line count (Factories producing Precious Metals) plus Kirara's tier-dependent bonus on top -- Pozëmka and Tuye both scale off this
  allPlacedNames: string[]; // every operator placed anywhere in the base -- Hoederer's "any work area" checks need this, not just same-room presence
}

export interface TradingPostSkillResult {
  orderEfficiency?: number; // decimal, e.g. 0.20 for +20%
  orderLimit?: number;
  selfMorale?: number; // decimal per hour, positive = more consumption -- THIS operator only, not room-wide
  allOperatorsBonus?: number; // decimal per hour, positive = more consumption -- applies to EVERY operator in the room, including self (e.g. Firewhistle's Warm-Up)
  overridesOthersEfficiency?: boolean;
  note?: string;
  formula?: string; // human-readable derivation of the orderEfficiency/orderLimit number above, shown in the "explain this facility" breakdown. Optional and populated incrementally, not required on every handler.
}


type Handler = (ctx: TradingPostContext) => TradingPostSkillResult;

