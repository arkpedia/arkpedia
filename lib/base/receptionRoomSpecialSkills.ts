export interface ReceptionRoomContext {
  manualValue?: number;
  sameRoomOperatorNames: string[]; // includes self
  filledCountThisRoom: number;
  dormitoryHasOperator: (name: string) => boolean; // is this named operator in ANY dormitory
  monsterMealTotal: number; // base-wide Monster Meal total, generated by Senshi's Diner in a Dormitory -- Laios's Clue search speed scales with this
  rampWindowHours: number; // real time window (until the first operator anywhere in this Reception Room dies from morale loss, capped at 24h) for Ines's ramping skill to average over
  resourceBonuses: Record<string, number>; // shared resource-chain values (e.g. Iana's Intelligence Reserve scaling)
  clueExchangeActive: boolean; // manual setting -- Caper/Cairn's "if in Clue Exchange" skills, a game mode this simulator can't detect on its own. Defaults to true.
}

export interface ClueSkillResult {
  clueSpeed?: number; // decimal, e.g. 0.20 for +20%
  selfMorale?: number; // Morale consumed per hour, THIS operator only -- not applied room-wide
  note?: string;
}

type Handler = (ctx: ReceptionRoomContext) => ClueSkillResult;

/** Keyed by "OperatorName|SkillName". Everyone NOT in here is handled
 * correctly already by the generic Clue Search Speed regex parser --
 * this only covers skills with a same-room condition, an "alone" bonus,
 * or a dependency on something this simulator can't track on its own. */
/** Time-weighted average of a step-ramping skill (e.g. Ines: flat at
 * 0.20 for the first hour, then +0.02/hr each hour after, capped at
 * 0.30) over an arbitrary window length in hours -- same verified
 * step semantics already used for the Factory ramping skills (Fang,
 * Kroos, Scene, Ceobe, Aroma). */
function stepValueAtHour(base: number, ratePerHour: number, cap: number, hourIndex: number): number {
  if (hourIndex === 0) return base;
  return Math.min(cap, base + ratePerHour * hourIndex);
}

function averageRampValue(base: number, ratePerHour: number, cap: number, windowHours: number): number {
  if (windowHours <= 0) return base;
  let total = 0;
  const fullHours = Math.floor(windowHours);
  for (let h = 0; h < fullHours; h++) {
    total += stepValueAtHour(base, ratePerHour, cap, h);
  }
  const remainder = windowHours - fullHours;
  if (remainder > 0) {
    total += stepValueAtHour(base, ratePerHour, cap, fullHours) * remainder;
  }
  return total / windowHours;
}

