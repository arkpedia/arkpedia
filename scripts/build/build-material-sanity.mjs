#!/usr/bin/env node
/**
 * Writes data/material-sanity.json: what one of each material costs in sanity, estimated from
 * Penguin Statistics' measured drop rates, for the Operator Planner's "Still needed" cards.
 *
 * An ESTIMATE, and labelled one wherever it shows. For each material it takes the cheapest
 * permanent stage to farm it on (stage sanity / drops per run), and where the material can
 * be crafted from the tiers below it (data/base-formulas.json, the recipes the planner
 * walks) it also prices the craft from those materials' own estimates and keeps the cheaper
 * of the two. A chip or chip pack has a third way, converting another class's (the Workshop trades
 * three of one for two of another), priced from the cheaper side of the trade. A material no stage drops and no recipe makes (a Chip Catalyst, a Dualchip) has
 * no entry: the planner shows nothing rather than a made-up number.
 *
 * This is NOT part of the scheduled refresh, on purpose. Measured rates were removed from the
 * stage pipeline (docs/development/data-pipelines.md) because they were the only input that
 * changed without the game changing, so a nightly run produced a diff most days from sample
 * counts nobody read. This table is regenerated by hand when the estimates are worth
 * refreshing (a new material tier, a stage rebalance, every few months):
 *
 *   node scripts/build/build-material-sanity.mjs            # fetches penguin-stats.io, three GETs
 *   node scripts/build/build-material-sanity.mjs --from DIR  # reads matrix/stages/items JSON saved in DIR
 *
 * Rules, each there for a reason:
 *  - Event stages (Penguin stageType ACTIVITY) are not counted: they close, and a plan priced
 *    on one is priced on a stage the reader may not be able to run.
 *  - Only a window of rates still open (no `end`) counts: the matrix also lists the closed ones, and
 *    the drop table a stage had last year is not the one it has.
 *  - A stage needs at least MIN_RUNS recorded runs. A rare drop on a stage with forty runs is
 *    noise, and the cheapest stage would be whichever one got lucky.
 *  - Quantities are averages per run: the matrix's `quantity` over its `times`.
 *  - The server is the one Penguin calls US, the Global client's. Its drop tables are the
 *    Global ones; a CN-only stage is not in its matrix.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const MIN_RUNS = 300;
const API = 'https://penguin-stats.io/PenguinStats/api/v2';
/** The recipes the planner follows down a tier (lib/planner/craft.ts WALKABLE): the chip trades are cycles. */
const WALKABLE = new Set(['F_EVOLVE', 'F_SKILL']);

const round = (n) => Math.round(n * 10) / 10;

/**
 * {name: {sanity, stage?, via}} from Penguin's three tables and the recipes.
 *
 * `matrix` is /result/matrix, `stages` /stages and `items` /items; `formulas` is
 * data/base-formulas.json; `names` the materials to price (the planner's catalogue).
 */
export function materialSanity({ matrix, stages, items, formulas, names }) {
  const stageById = new Map(stages.map((stage) => [stage.stageId, stage]));
  const nameById = new Map(items.map((item) => [item.itemId, item.name_i18n?.en ?? item.name]));

  /* Cheapest farm per item name: { sanity, stage }. */
  const farm = new Map();
  for (const row of matrix) {
    const stage = stageById.get(row.stageId);
    const name = nameById.get(row.itemId);
    /* `end` set means Penguin closed that window of the stage's rates: an old rotation or a
       drop table the game has since changed. Only the current window prices a farm. */
    if (!stage || !name || stage.stageType === 'ACTIVITY' || row.end != null) continue;
    if (!(stage.apCost > 0) || !(row.times >= MIN_RUNS) || !(row.quantity > 0)) continue;
    const sanity = stage.apCost * row.times / row.quantity;
    const best = farm.get(name);
    if (!best || sanity < best.sanity) farm.set(name, { sanity, stage: stage.code });
  }

  const out = new Map();
  const walking = new Set();
  /* The estimate for one material: its farm cost or its craft cost, the cheaper. */
  function estimate(name) {
    if (out.has(name)) return out.get(name);
    let best = farm.has(name) ? { sanity: farm.get(name).sanity, stage: farm.get(name).stage, via: 'farm' } : null;
    const recipe = formulas[name];
    if (recipe && WALKABLE.has(recipe.type) && !walking.has(name)) {
      walking.add(name);
      let sum = 0;
      let complete = true;
      for (const cost of recipe.costs) {
        if (cost.name === 'LMD') continue;
        const part = estimate(cost.name);
        if (!part) { complete = false; break; }
        sum += part.sanity * cost.count;
      }
      walking.delete(name);
      if (complete && recipe.count > 0) {
        const crafted = sum / recipe.count;
        if (!best || crafted < best.sanity) best = { sanity: crafted, via: 'craft' };
      }
    }
    out.set(name, best);
    return best;
  }

  for (const name of names) estimate(name);

  /* Chips and chip packs have a second way in beside their stage: the Workshop trades three of
     one class for two of another (F_ASC). Those trades are a cycle, which is why the planner never
     walks them, but a price is only a number: relax every chip's cost against 1.5x its source's
     until nothing gets cheaper. A trade never beats a stage that is already cheap, and one
     class's cheap stage lowers the price of the class it trades into. */
  const trades = Object.entries(formulas).filter(([, recipe]) => recipe.type === 'F_ASC');
  for (let pass = 0, changed = true; changed && pass < 50; pass++) {
    changed = false;
    for (const [name, recipe] of trades) {
      let sum = 0;
      let complete = true;
      for (const cost of recipe.costs) {
        const part = cost.name === 'LMD' ? { sanity: 0 } : out.get(cost.name);
        if (!part) { complete = false; break; }
        sum += part.sanity * cost.count;
      }
      if (!complete || !(recipe.count > 0)) continue;
      const converted = sum / recipe.count;
      const have = out.get(name);
      if (!have || converted < have.sanity - 1e-9) { out.set(name, { sanity: converted, via: 'convert' }); changed = true; }
    }
  }

  const result = {};
  for (const name of names) {
    const entry = out.get(name);
    if (!entry) continue;
    result[name] = { sanity: round(entry.sanity), via: entry.via, ...(entry.stage ? { stage: entry.stage } : {}) };
  }
  return result;
}

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

async function getJson(endpoint) {
  const response = await fetch(`${API}/${endpoint}`, { headers: { 'user-agent': 'arkpedia-material-sanity (build script)' } });
  if (!response.ok) throw new Error(`Penguin Statistics ${endpoint}: HTTP ${response.status}`);
  return response.json();
}

async function main() {
  const root = process.cwd();
  const from = process.argv.includes('--from') ? process.argv[process.argv.indexOf('--from') + 1] : null;
  const server = 'US';
  const matrix = from ? readJson(path.join(from, 'matrix.json')).matrix : (await getJson(`result/matrix?server=${server}&show_closed_zones=false`)).matrix;
  const stages = from ? readJson(path.join(from, 'stages.json')) : await getJson(`stages?server=${server}`);
  const items = from ? readJson(path.join(from, 'items.json')) : await getJson('items');
  const formulas = readJson(path.join(root, 'data', 'base-formulas.json'));
  const catalogue = readJson(path.join(root, 'data', 'material-catalogue.json'));
  const names = catalogue.order.filter((name) => name !== 'EXP' && name !== 'LMD');

  const estimates = materialSanity({ matrix, stages, items, formulas, names });
  if (Object.keys(estimates).length < 40) {
    console.error(`Refusing to write: only ${Object.keys(estimates).length} of ${names.length} materials priced. Penguin's tables may have changed shape.`);
    process.exit(1);
  }
  const dest = path.join(root, 'data', 'material-sanity.json');
  const table = {
    about: 'Estimated sanity per material from Penguin Statistics drop rates (scripts/build/build-material-sanity.mjs). An estimate: the cheapest permanent stage, or the craft from cheaper tiers where that costs less. Regenerated by hand, not by the scheduled refresh.',
    source: { name: 'Penguin Statistics', url: 'https://penguin-stats.io', server, minRuns: MIN_RUNS, fetchedAt: new Date().toISOString().slice(0, 10) },
    items: estimates,
  };
  fs.writeFileSync(dest, JSON.stringify(table, null, 2) + '\n');
  const missing = names.filter((name) => !(name in estimates));
  console.log(`Wrote ${Object.keys(estimates).length} of ${names.length} materials -> ${path.relative(root, dest)}`);
  console.log(`No estimate (no permanent stage drops it, no recipe the planner walks): ${missing.join(', ') || 'none'}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => { console.error(error); process.exit(1); });
}
