#!/usr/bin/env node
/**
 * Writes data/permanent-rewards.json: the material rewards of the game's permanent modes, for the
 * Operator Planner's Farming method (lib/planner/farmingMethod.ts), whose "Permanent content" toggles
 * count what a reader has not yet claimed.
 *
 *   node scripts/build/build-permanent-rewards.mjs            # fetches the public gamedata mirrors
 *   node scripts/build/build-permanent-rewards.mjs --from DIR  # reads the tables saved in DIR
 *
 * Each mode is a list of rewards, each with the id the game's save marks claimed (so an imported
 * account can say which are done) and the materials in it:
 *  - IS1..IS6 (Integrated Strategies, roguelike_topic_table rogue_N): the milestone track,
 *    `milestones[]` by its bp_level id. The track pays more than one thing per level; only materials
 *    the depot tracks are kept, so LMD, EXP, outfits and furniture are not here.
 *  - RA2 (sandbox_1, "Tales Within the Sand"): the challenge-mode day rewards, `challengeModeRewardData`.
 *    Its monthly rush rewards are left out: a month that has ended can no longer be claimed.
 *  - RA3 (sandbox_2, "Relaunch Anchor"): the base upgrade rewards, `basementUpdateDatas[].rewards`.
 *  - SSS (Stationary Security Service, climb_tower_table): every season's missions, `missionData`.
 * Global's table (ArknightsAssets/ArknightsGamedata, en) first; a mode or reward it does not have yet
 * comes from CN (Kengxxiao/ArknightsGameData, zh_CN) and is marked `cn`, because a Global reader cannot
 * claim it yet. Ids become names through data/import-aliases.json, the depot's own vocabulary.
 *
 * Regenerated by hand when a mode or season ships, not by the scheduled refresh: it changes only when
 * the game adds one. Its claim ids are what lib/account/permanentClaims.ts reads out of a save.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const MIRRORS = {
  en: 'https://raw.githubusercontent.com/ArknightsAssets/ArknightsGamedata/master/en/gamedata/excel',
  cn: 'https://raw.githubusercontent.com/Kengxxiao/ArknightsGameData/master/zh_CN/gamedata/excel',
};
const TABLES = ['roguelike_topic_table', 'sandbox_perm_table', 'climb_tower_table'];

/** The modes the planner offers, in the order it lists them. */
export const MODES = [
  { id: 'is-1', label: 'IS1', kind: 'is', topic: 'rogue_1' },
  { id: 'is-2', label: 'IS2', kind: 'is', topic: 'rogue_2' },
  { id: 'is-3', label: 'IS3', kind: 'is', topic: 'rogue_3' },
  { id: 'is-4', label: 'IS4', kind: 'is', topic: 'rogue_4' },
  { id: 'is-5', label: 'IS5', kind: 'is', topic: 'rogue_5' },
  { id: 'is-6', label: 'IS6', kind: 'is', topic: 'rogue_6' },
  { id: 'ra-2', label: 'RA2', kind: 'ra-challenge', topic: 'sandbox_1' },
  { id: 'ra-3', label: 'RA3', kind: 'ra-base', topic: 'sandbox_2' },
  { id: 'sss', label: 'SSS missions', kind: 'sss', topic: 'climb_tower' },
];

const quantity = (n) => (Number.isFinite(Number(n)) && Number(n) > 0 ? Math.floor(Number(n)) : 0);

/** {materialName: count} from game reward entries ({id, count, type}), the depot's materials only. */
function materialsOf(entries, byItemId, dropped) {
  const out = {};
  for (const entry of entries ?? []) {
    if (!entry || entry.type !== 'MATERIAL') continue;
    const name = byItemId[String(entry.id)];
    if (!name) { dropped.add(String(entry.id)); continue; }
    const count = quantity(entry.count);
    if (count > 0) out[name] = (out[name] ?? 0) + count;
  }
  return Object.fromEntries(Object.keys(out).sort().map((key) => [key, out[key]]));
}

/** One table's rewards for one mode: [{id, materials}], from a region's tables. */
function rewardsFor(mode, tables, byItemId, dropped) {
  const list = [];
  if (mode.kind === 'is') {
    for (const milestone of tables.roguelike_topic_table?.details?.[mode.topic]?.milestones ?? []) {
      if (milestone.itemType !== 'MATERIAL') continue;
      list.push({ id: milestone.id, materials: materialsOf([{ id: milestone.itemID, count: milestone.itemCount, type: 'MATERIAL' }], byItemId, dropped) });
    }
  } else if (mode.kind === 'ra-challenge') {
    const rewards = tables.sandbox_perm_table?.detail?.SANDBOX_V2?.[mode.topic]?.challengeModeData?.challengeModeRewardData ?? {};
    for (const reward of Object.values(rewards)) list.push({ id: reward.rewardId, materials: materialsOf(reward.rewardItemList, byItemId, dropped) });
  } else if (mode.kind === 'ra-base') {
    for (const level of tables.sandbox_perm_table?.detail?.SANDBOX_V3?.[mode.topic]?.basementUpdateDatas ?? []) {
      list.push({ id: level.baseLevelId, materials: materialsOf(level.rewards, byItemId, dropped) });
    }
  } else if (mode.kind === 'sss') {
    for (const mission of Object.values(tables.climb_tower_table?.missionData ?? {})) list.push({ id: mission.id, materials: materialsOf(mission.rewards, byItemId, dropped) });
  }
  return list.filter((reward) => typeof reward.id === 'string' && reward.id && Object.keys(reward.materials).length);
}

/**
 * The permanent-rewards table from Global's and CN's tables.
 * `tables` is { en, cn }, each { roguelike_topic_table, sandbox_perm_table, climb_tower_table }.
 */
export function buildPermanentRewards({ tables, byItemId }) {
  const dropped = new Set();
  const modes = [];
  for (const mode of MODES) {
    const global = rewardsFor(mode, tables.en, byItemId, dropped);
    const cn = rewardsFor(mode, tables.cn, byItemId, dropped);
    const have = new Set(global.map((reward) => reward.id));
    const rewards = [...global, ...cn.filter((reward) => !have.has(reward.id)).map((reward) => ({ ...reward, cn: true }))];
    if (!rewards.length) continue;
    modes.push({ id: mode.id, label: mode.label, kind: mode.kind, topic: mode.topic, global: global.length > 0, rewards });
  }
  return { modes, dropped: [...dropped].sort() };
}

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

async function fetchTables(region, into) {
  fs.mkdirSync(into, { recursive: true });
  for (const name of TABLES) {
    const file = path.join(into, `${name}.json`);
    if (fs.existsSync(file)) continue;
    const response = await fetch(`${MIRRORS[region]}/${name}.json`, { headers: { 'user-agent': 'arkpedia-permanent-rewards (build script)' } });
    if (!response.ok) throw new Error(`${region} ${name}: HTTP ${response.status}`);
    fs.writeFileSync(file, Buffer.from(await response.arrayBuffer()));
  }
}

async function main() {
  const root = process.cwd();
  const from = process.argv.includes('--from') ? process.argv[process.argv.indexOf('--from') + 1] : null;
  const dir = from ?? path.join(root, '.cache', 'permanent-rewards');
  if (!from) { await fetchTables('en', path.join(dir, 'en')); await fetchTables('cn', path.join(dir, 'cn')); }
  const load = (prefix, region) => Object.fromEntries(TABLES.map((name) => [name, readJson(from ? path.join(dir, `${prefix}${name}.json`) : path.join(dir, region, `${name}.json`))]));
  const tables = { en: load('', 'en'), cn: load('cn_', 'cn') };
  const aliases = readJson(path.join(root, 'data', 'import-aliases.json'));
  const { modes, dropped } = buildPermanentRewards({ tables, byItemId: aliases.byItemId });
  if (modes.length < MODES.length) {
    console.error(`Refusing to write: only ${modes.length} of ${MODES.length} modes had rewards (${MODES.filter((m) => !modes.some((x) => x.id === m.id)).map((m) => m.id).join(', ')}). The tables may have changed shape.`);
    process.exit(1);
  }
  const dest = path.join(root, 'data', 'permanent-rewards.json');
  const table = {
    about: 'Material rewards of the permanent modes (scripts/build/build-permanent-rewards.mjs): IS milestones, RA2 challenge days, RA3 base levels, SSS season missions. `cn` marks what only CN has so far. Regenerated by hand when a mode or season ships.',
    modes,
  };
  fs.writeFileSync(dest, JSON.stringify(table, null, 2) + '\n');
  for (const mode of modes) {
    const totals = {};
    for (const reward of mode.rewards) for (const [name, n] of Object.entries(reward.materials)) totals[name] = (totals[name] ?? 0) + n;
    console.log(`${mode.label.padEnd(13)} ${String(mode.rewards.length).padStart(3)} rewards (${mode.rewards.filter((r) => r.cn).length} CN only), ${Object.keys(totals).length} materials, ${Object.values(totals).reduce((a, b) => a + b, 0)} items${mode.global ? '' : ' [not on Global]'}`);
  }
  console.log(`Not in the depot's vocabulary (left out): ${dropped.join(', ') || 'none'}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => { console.error(error); process.exit(1); });
}
